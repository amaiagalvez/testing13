#!/usr/bin/env bash
#
# Enlaza las skills y genera los agentes con frontmatter compatible con Claude Code.
# Ejecutable desde cualquier directorio; acepta una raíz de repositorio opcional.

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ $# -gt 0 ]]; then
    root="$1"
else
    root="$script_dir"
    while [[ "$root" != "/" && ( ! -d "$root/.github/agents" || ! -d "$root/.github/skills" ) ]]; do
        root="$(dirname "$root")"
    done
fi
cd "$root"

AGENTS_SRC=".github/agents"
AGENTS_DEST=".claude/agents"
SKILLS_SRC=".github/skills"
SKILLS_DEST=".claude/skills"
GENERATED_MARKER="Generated from .github/agents by testing13/agents/link-claude-assets.sh."

if [[ ! -d "$AGENTS_SRC" || ! -d "$SKILLS_SRC" ]]; then
    printf 'Error: %s and/or %s not found under %s.\n' "$AGENTS_SRC" "$SKILLS_SRC" "$root" >&2
    exit 1
fi

mkdir -p "$AGENTS_DEST"

# Elimina enlaces previos y solo los archivos normales que este script generó.
while IFS= read -r -d '' link_path; do
    rm -f "$link_path"
done < <(find "$AGENTS_DEST" -mindepth 1 -maxdepth 1 -type l -print0)

while IFS= read -r -d '' generated_file; do
    if grep -qF "$GENERATED_MARKER" "$generated_file"; then
        rm -f "$generated_file"
    fi
done < <(find "$AGENTS_DEST" -mindepth 1 -maxdepth 1 -type f -name '*.md' -print0)

if [[ -e "$SKILLS_DEST" && ! -L "$SKILLS_DEST" ]]; then
    printf 'Error: %s exists and is not a symlink; it will not be replaced.\n' "$SKILLS_DEST" >&2
    exit 1
fi
if [[ -L "$SKILLS_DEST" ]]; then
    rm -f "$SKILLS_DEST"
fi
ln -s "../$SKILLS_SRC" "$SKILLS_DEST"

printf 'Agents (.github/agents -> .claude/agents; adapted frontmatter)\n'
for src in "$AGENTS_SRC"/*.agent.md; do
    [[ -e "$src" ]] || continue
    id="$(basename "$src" .agent.md)"
    description="$(awk '/^description:[[:space:]]*/ { print; exit }' "$src")"

    if [[ -z "$description" ]]; then
        printf 'Error: description is missing in %s.\n' "$src" >&2
        exit 1
    fi

    if [[ "$id" == "review-orchestrator" ]]; then
        tools="Read, Grep, Glob, Agent, Bash, Write"
    else
        tools="Read, Grep, Glob"
    fi

    dest="$AGENTS_DEST/$id.md"
    if [[ -e "$dest" || -L "$dest" ]]; then
        printf 'Error: %s already exists and was not generated by this script; it will not be replaced.\n' "$dest" >&2
        exit 1
    fi

    temp_file="$(mktemp "$AGENTS_DEST/.${id}.XXXXXX")"
    {
        printf '%s\n' '---'
        printf 'name: %s\n' "$id"
        printf '%s\n' "$description"
        printf 'tools: %s\n' "$tools"
        printf '%s\n' '---'
        printf '<!-- %s -->\n\n' "$GENERATED_MARKER"
        awk '
            NR == 1 && $0 == "---" { frontmatter = 1; next }
            frontmatter && $0 == "---" { frontmatter = 0; body = 1; next }
            body { print }
            END { if (!body) exit 1 }
        ' "$src"
    } > "$temp_file"
    mv -f "$temp_file" "$dest"
    printf '  + %s\n' "$id"
done

printf '\nSkills: %s -> %s\n' "$SKILLS_DEST" "$SKILLS_SRC"
printf 'Claude agent files are generated; edit their sources in %s.\n' "$AGENTS_SRC"
